/**
 * Per-quotation verification register.
 *
 * Search Console shows this archive's only top-3 rankings all sit in the
 * "quote source" family: readers arrive holding a sentence, a name, or a
 * fragment, and they want the locator. The pages that rank for those queries
 * are the ones that answer attribution questions explicitly instead of only
 * presenting the passage.
 *
 * This register holds the material that answer needs and that no scraper site
 * has: the original-language wording where a single original exists, the
 * variants that circulate in place of it, and the specific thing readers get
 * wrong about who said it and in what sense.
 *
 * Deliberately a register, not a template. Nothing here is generated by
 * pattern: an entry exists only where there is something true and specific to
 * say. Pages without an entry render the citation block alone rather than
 * filler, because a boilerplate paragraph repeated across 690 pages is the
 * exact thin-content signature that triggered the August quality re-evaluation.
 *
 * Adding a batch: append entries, then add the IDs to VERIFICATION_BATCHES.
 */

