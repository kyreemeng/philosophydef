/**
 * The two dates the corpus itself last moved, used as the fallback “last
 * verified” for passages with no per-quote register entry.
 *
 * They are different on purpose. Q0001–Q0499 with no written commentary have
 * not changed since the corpus stabilised on 2026-08-26. The later quotations,
 * and the legacy passages that received passage-specific commentary, were
 * written on 2026-08-30. Stamping one date on all of them would tell a crawler
 * that nine hundred pages changed on the same day, which is the exact signal
 * the sitemap work exists to stop sending.
 */
export const LEGACY_CORPUS_DATE = "2026-08-26";
export const CORPUS_UNLOCK_DATE = "2026-08-30";

export function corpusReviewDate(id: string, hasOwnCommentary: boolean) {
  const numeric = Number(id.replace(/^Q/i, ""));
  if (Number.isFinite(numeric) && numeric > 499) return CORPUS_UNLOCK_DATE;
  return hasOwnCommentary ? CORPUS_UNLOCK_DATE : LEGACY_CORPUS_DATE;
}

